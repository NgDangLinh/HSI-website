import fs from 'fs';
import path from 'path';
import https from 'https';

const WP_URL = process.env.NEXT_PUBLIC_WORDPRESS_URL || 'https://hsicorp.com.vn';
const TARGET_IMG_DIR = path.resolve('public/images/posts');
const TARGET_DATA_FILE = path.resolve('lib/data/mockPosts.ts');

if (!fs.existsSync(TARGET_IMG_DIR)) {
  fs.mkdirSync(TARGET_IMG_DIR, { recursive: true });
}

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https.get(
      url,
      {
        headers: {
          'User-Agent':
            'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
          Accept: 'application/json',
        },
      },
      (res) => {
        if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          return fetchJson(res.headers.location).then(resolve).catch(reject);
        }
        let data = '';
        res.on('data', (chunk) => (data += chunk));
        res.on('end', () => {
          try {
            resolve(JSON.parse(data));
          } catch (e) {
            reject(new Error(`Failed to parse JSON from ${url}: ${e.message}`));
          }
        });
      }
    ).on('error', reject);
  });
}

function downloadImage(url, dest) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return downloadImage(res.headers.location, dest).then(resolve).catch(reject);
      }
      if (res.statusCode !== 200) {
        return reject(new Error(`HTTP ${res.statusCode}`));
      }
      const fileStream = fs.createWriteStream(dest);
      res.pipe(fileStream);
      fileStream.on('finish', () => {
        fileStream.close();
        resolve();
      });
    }).on('error', reject);
  });
}

function cleanHtmlText(text) {
  if (!text) return '';
  return text
    .replace(/<[^>]*>?/gm, '')
    .replace(/&amp;/g, '&')
    .replace(/&#8211;/g, '–')
    .replace(/&#8212;/g, '—')
    .replace(/&#8216;/g, "'")
    .replace(/&#8217;/g, "'")
    .replace(/&#8220;/g, '"')
    .replace(/&#8221;/g, '"')
    .replace(/&quot;/g, '"')
    .replace(/&#038;/g, '&')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function formatDate(isoString) {
  if (!isoString) return '';
  const d = new Date(isoString);
  const day = String(d.getDate()).padStart(2, '0');
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const year = d.getFullYear();
  return `${day}/${month}/${year}`;
}

async function syncPosts() {
  console.log(`📡 Fetching posts from ${WP_URL}/wp-json/wp/v2/posts?categories=45&_embed ...`);
  const rawPosts = await fetchJson(`${WP_URL}/wp-json/wp/v2/posts?categories=45&_embed&per_page=100`);

  if (!Array.isArray(rawPosts) || rawPosts.length === 0) {
    console.error('❌ No posts returned from WordPress API.');
    return;
  }

  console.log(`✅ Received ${rawPosts.length} posts from WordPress API.`);

  const mappedPosts = [];

  for (let i = 0; i < rawPosts.length; i++) {
    const p = rawPosts[i];
    const id = p.id;
    const title = cleanHtmlText(p.title?.rendered || '');
    const slug = p.slug || `post-${id}`;
    const excerpt = cleanHtmlText(p.excerpt?.rendered || '');
    const rawContent = p.content?.rendered || '';
    const date = formatDate(p.date);
    const author = 'Ban Truyền Thông HSI';
    const category = 'Truyền thông';

    let remoteImgUrl = '';
    let localImgFilename = '';

    if (p._embedded && p._embedded['wp:featuredmedia'] && p._embedded['wp:featuredmedia'][0]) {
      remoteImgUrl = p._embedded['wp:featuredmedia'][0].source_url || '';
    }

    if (remoteImgUrl) {
      try {
        const ext = path.extname(new URL(remoteImgUrl).pathname) || '.jpg';
        localImgFilename = `post-${id}${ext}`;
        const localDest = path.join(TARGET_IMG_DIR, localImgFilename);

        console.log(`⬇️ Downloading featured image for [${id}] ${title.slice(0, 30)}...`);
        await downloadImage(remoteImgUrl, localDest);
        console.log(`   Saved as ${localImgFilename}`);
      } catch (err) {
        console.warn(`   ⚠️ Failed to download image ${remoteImgUrl}: ${err.message}`);
        localImgFilename = '';
      }
    }

    const finalImageUrl = localImgFilename ? `/images/posts/${localImgFilename}` : remoteImgUrl;

    mappedPosts.push({
      id,
      title,
      slug,
      excerpt,
      content: rawContent,
      date,
      category,
      imageUrl: finalImageUrl,
      remoteImageUrl: remoteImgUrl,
      author,
    });
  }

  // Generate TypeScript file
  const tsContent = `// Auto-generated by scripts/sync-posts.mjs on ${new Date().toISOString()}
// Contains authentic articles from hsicorp.com.vn (Category: Truyền thông)

export interface NewsPost {
  id: number;
  title: string;
  slug: string;
  excerpt: string;
  content: string;
  date: string;
  category: string;
  imageUrl: string;
  remoteImageUrl?: string;
  author: string;
}

export const MOCK_POSTS: NewsPost[] = ${JSON.stringify(mappedPosts, null, 2)};
`;

  fs.writeFileSync(TARGET_DATA_FILE, tsContent, 'utf-8');
  console.log(`🎉 Successfully synced ${mappedPosts.length} posts to ${TARGET_DATA_FILE}!`);
}

syncPosts().catch((err) => {
  console.error('Fatal sync error:', err);
  process.exit(1);
});

